#!/usr/bin/env python3
"""Generate the unchanged-data consumer table from archived held-out results.

Run: python3 tools/consumer-stats.py
All costs include correct and incorrect scored answers. Tokens per correct
answer divide total scored tokens by the number of correct answers; they are
not the mean token count of successful sessions. Learning costs are separate.
"""
import gzip
import json
from math import isclose
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
METHODS = [
    ('middle', 'No-Memory', '无指标记忆'),
    ('traj-global', 'Traj-Retrieve', '轨迹检索'),
    ('metric-global-snap', 'MAVRA', 'MAVRA'),
]


def load():
    synthetic = ROOT / 'exp/2026-10-10-scenarios-q5'
    tpch = ROOT / 'exp/2026-10-11-generality/e2e'
    syn = json.loads((synthetic / 'holdout-cost.json').read_text())['methods']
    with gzip.open(tpch / 'outcomes.json.gz', 'rt', encoding='utf-8') as source:
        records = json.load(source)['records']
    tp = {}
    for mode, *_ in METHODS:
        rows = [r for r in records if r['phase'] == 'holdout'
                and r['outcome'] != 'error' and r['mode'] == mode]
        tp[mode] = []
        for run in sorted({r['run'] for r in rows}):
            rs = [r for r in rows if r['run'] == run]
            tp[mode].append(dict(
                n=len(rs), correct=sum(r['outcome'] == 'correct' for r in rs),
                s_sum=sum(r['seconds'] for r in rs),
                tok_sum=sum(r['input_tokens'] + r['output_tokens'] for r in rs)))
    return [(synthetic, syn, 5, 'Synthetic retail', '合成零售数据'),
            (tpch, tp, 3, 'TPC-H SF1', 'TPC-H SF1')]


def render():
    lines = ['% Generated by tools/consumer-stats.py; do not edit.',
             r'\newcommand{\ConsumerCostRows}{%']
    for path, methods, nruns, en, zh in load():
        reference = json.loads((path / 'scen-stats.json').read_text())['methods']
        label = rf'\bt{{{en}: {nruns} runs}}{{{zh}：{nruns} 次运行}}'
        lines.append(r'\multicolumn{5}{@{}l@{}}{\textbf{' + label + r'}}\\')
        lines.append(r'\midrule')
        for mode, short, chinese in METHODS:
            runs = methods[mode]
            assert len(runs) == nruns, (path, mode)
            n = sum(r['n'] for r in runs)
            correct = sum(r['correct'] for r in runs)
            seconds = sum(r['s_sum'] for r in runs)
            tokens = sum(r['tok_sum'] for r in runs)
            assert n == nruns * 25, (path, mode, n)
            assert isclose(correct / n, reference[mode]['holdout']['acc']), (path, mode)
            values = [seconds / n, tokens / n / 1000, 100 * correct / n,
                      tokens / correct / 1000]
            cells = [f'{v:.1f}' for v in values]
            name = short if short == chinese else rf'\bhl{{{short}}}{{{chinese}}}'
            if mode == 'metric-global-snap':
                name = rf'\textbf{{{name}}}'
            lines.append(name + ' & ' + ' & '.join(cells) + r'\\')
        lines.append(r'\addlinespace')
    return '\n'.join(lines + ['}']) + '\n'


if __name__ == '__main__':
    output = ROOT / 'overleaf/gen/consumer-cost.tex'
    output.write_text(render(), encoding='utf-8')
    print(output)
