#!/usr/bin/env python3
"""Render or check the experiment index using only the Python standard library."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'exp/catalog.json'
INDEX = ROOT / 'exp/README.md'
STATUSES = {'current': '当前采用', 'supporting': '补充证据', 'historical': '历史批次'}


def validate(catalog):
    entries = catalog['experiments']
    ids = [entry['id'] for entry in entries]
    if len(ids) != len(set(ids)):
        raise ValueError('Duplicate experiment IDs')
    directories = {p.name for p in (ROOT / 'exp').iterdir() if p.is_dir()}
    if set(ids) != directories:
        raise ValueError(f'Catalog/directory mismatch: {sorted(set(ids) ^ directories)}')
    for entry in entries:
        if not re.fullmatch(r'\d{4}-\d{2}-\d{2}-[a-z0-9-]+', entry['id']):
            raise ValueError(f'Invalid experiment ID: {entry["id"]}')
        if entry['status'] not in STATUSES:
            raise ValueError(f'Unknown status: {entry["status"]}')
        for field in ('title', 'scope', 'raw_data', 'code_record'):
            if not entry[field].strip():
                raise ValueError(f'{entry["id"]}: missing {field}')
        paths = [f'exp/{entry["id"]}/README.md', *entry['evidence'], *entry['analysis'], *entry['outputs']]
        for value in paths:
            path = Path(value)
            if path.is_absolute() or '..' in path.parts or not (ROOT / path).is_file():
                raise ValueError(f'{entry["id"]}: missing or invalid file: {value}')
    return entries


def link(path):
    relative = path[4:] if path.startswith('exp/') else '../' + path
    return f'[{Path(path).name}]({relative})'


def render(entries):
    lines = [
        '# 实验索引', '',
        '<!-- Generated by tools/experiment-index.py from exp/catalog.json; edit the catalog. -->', '',
        '本索引覆盖全部日期目录。采用范围依据当前稿件和实验协议；同一目录可包含试跑、被替换运行和正式结果，具体排除规则见各条目。', '',
        '原始运行输出默认写入被 Git 忽略的 `results/`，经过整理的证据保存在这里。远端路径是位置记录，不表示本机已有完整副本。当前清单见 [catalog.json](catalog.json)。', '',
    ]
    for status, label in STATUSES.items():
        lines += [f'## {label}', '', '| 实验 | 用途与采用范围 |', '| --- | --- |']
        for entry in entries:
            if entry['status'] == status:
                lines.append(f'| [{entry["id"]}]({entry["id"]}/README.md)<br>{entry["title"]} | {entry["scope"]} |')
        lines.append('')
    lines += ['## 证据与复现入口', '',
              '| 实验 | 本地证据 | 分析脚本 | 生成的论文文件 |', '| --- | --- | --- | --- |']
    for entry in entries:
        columns = ['、'.join(link(p) for p in entry[field]) or '—' for field in ('evidence', 'analysis', 'outputs')]
        lines.append(f'| {entry["id"]} | ' + ' | '.join(columns) + ' |')
    lines += ['', '## 原始数据与代码版本记录', '',
              '| 实验 | 原始数据位置与可用性 | 代码版本、配置与命令记录 |', '| --- | --- | --- |']
    for entry in entries:
        lines.append(f'| {entry["id"]} | {entry["raw_data"]} | {entry["code_record"]} |')
    lines += ['', '## 维护索引', '',
              '修改 `exp/catalog.json` 后，在仓库根目录运行 `python3 tools/experiment-index.py`；`--check` 检查目录覆盖、文件引用和索引是否同步，不执行实验。', '',
              '新增实验的记录要求见 [仓库维护约定](../docs/development/repository.md)。早期运行数值、提交号与服务器环境保留在 [历史索引](../docs/history/experiment-index-2026-10-03.md)。', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='validate without writing')
    args = parser.parse_args()
    try:
        entries = validate(json.loads(CATALOG.read_text(encoding='utf-8')))
        content = render(entries)
        if args.check:
            if not INDEX.is_file() or INDEX.read_text(encoding='utf-8') != content:
                raise ValueError('exp/README.md is stale; run python3 tools/experiment-index.py')
        else:
            INDEX.write_text(content, encoding='utf-8')
    except (ValueError, KeyError, OSError) as error:
        parser.exit(1, f'{error}\n')
    print(f'{len(entries)} experiments: coverage, references, and index OK')


if __name__ == '__main__':
    main()
