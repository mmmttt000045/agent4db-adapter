#!/usr/bin/env python3
"""ReFoRCE 作使用者的统计，按 exp/2026-10-12-reforce/README.md 中预先写定的分析方案。

用法：python3 tools/reforce-stats.py --scen results/reforce-20261012 [--json OUT] [--reps 4000] [--tex-out overleaf/gen]
--tex-out 时另写 reforce.tex（\\Rf* 数值宏）。计分、分组、正确率与整群自助法与场景主实验相同（复用 tools/scen-stats.py）。

- 预先声明的比较：(a) 条件覆盖的破坏下 ReFoRCE + MAVRA 与其余三组之差；(b) 留出题上 ReFoRCE + MAVRA − ReFoRCE；
  (c) 全部情形下 ReFoRCE + MAVRA − ReFoRCE。
- 另报每题的 LLM 调用数、输入 token 与耗时（ReFoRCE 一道题的全部候选与步骤之和），以及每次运行各组的正确率。
"""

import argparse
import collections
import importlib.util
import json
import os
import random

spec = importlib.util.spec_from_file_location("scen_stats", os.path.join(os.path.dirname(os.path.abspath(__file__)), "scen-stats.py"))
S = importlib.util.module_from_spec(spec)
spec.loader.exec_module(S)

METHODS = ["reforce", "reforce-traj", "reforce-static", "reforce-mavra"]
NAMES = {"reforce": "ReFoRCE", "reforce-traj": "ReFoRCE + retrieved examples",
         "reforce-static": "ReFoRCE + definitions written once", "reforce-mavra": "ReFoRCE + MAVRA"}
KEY = {"reforce": "Alone", "reforce-traj": "Traj", "reforce-static": "Static", "reforce-mavra": "Cond"}


def per_task(cell):
    """计分题的 LLM 调用数、输入 token、耗时（服务端失败不计）。"""
    calls, toks, secs = [], [], []
    for r in cell["d"]["records"]:
        if r["phase"] == "learn" or r["phase"].endswith("-relearn") or r["outcome"] == "error":
            continue
        calls.append(r["run"]["steps"])
        toks.append(r["run"]["input_tokens"])
        secs.append(r["run"]["seconds"])
    return calls, toks, secs


def tex(res, out):
    pct = lambda v: f"{100 * v:.0f}" if v is not None else "--"
    q = {"RfCells": sum(res["cells"].values()), "RfProviderErrors": sum(r["provider_errors"] for r in res["methods"].values())}
    for m, r in res["methods"].items():
        k = KEY[m]
        for g in S.GROUPS:
            q[f"Rf{k}{g.capitalize()}"] = pct(r[g]["acc"])
            lo, hi = r[g]["ci95"]
            q[f"Rf{k}{g.capitalize()}Lo"] = pct(lo)
            q[f"Rf{k}{g.capitalize()}Hi"] = pct(hi)
            runs = [v for v in r["run_acc"][g] if v is not None]
            q[f"Rf{k}{g.capitalize()}Min"] = pct(min(runs)) if runs else "--"
            q[f"Rf{k}{g.capitalize()}Max"] = pct(max(runs)) if runs else "--"
        q[f"Rf{k}StaleModeled"] = r["stale_tasks"]["modeled"]
        q[f"Rf{k}Calls"] = f"{r['llm_calls_per_task']:.1f}" if r["llm_calls_per_task"] else "--"
        q[f"Rf{k}TokK"] = f"{r['input_tokens_per_task'] / 1000:.0f}" if r["input_tokens_per_task"] else "--"
        q[f"Rf{k}Secs"] = f"{r['seconds_per_task']:.0f}" if r["seconds_per_task"] else "--"
    names = {"a1 modeled: +MAVRA - alone": "RfCmpModeledAlone", "a2 modeled: +MAVRA - examples": "RfCmpModeledTraj",
             "a3 modeled: +MAVRA - written once": "RfCmpModeledStatic", "b holdout: +MAVRA - alone": "RfCmpHoldoutAlone",
             "c all: +MAVRA - alone": "RfCmpAllAlone"}
    for label, name in names.items():
        c = res["comparisons"].get(label)
        if c:
            q[name] = f"{100 * c['diff']:.0f}"
            q[name + "Lo"] = f"{100 * c['ci95'][0]:.0f}"
            q[name + "Hi"] = f"{100 * c['ci95'][1]:.0f}"
    with open(os.path.join(out, "reforce.tex"), "w", encoding="utf-8") as f:
        f.write("% generated by tools/reforce-stats.py; do not edit\n")
        for k, v in q.items():
            f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--scen", required=True)
    ap.add_argument("--json", default=None)
    ap.add_argument("--reps", type=int, default=4000)
    ap.add_argument("--tex-out", default=None)
    o = ap.parse_args()
    raw, skipped = S.load(o.scen)
    by, timing = collections.defaultdict(list), collections.defaultdict(lambda: ([], [], []))
    for c in raw:
        m = c["d"]["mode"]
        by[m].append(S.cell_stats(c))
        for acc, xs in zip(timing[m], per_task(c)):
            acc.extend(xs)
    rnd = random.Random(20261012)
    res = {"cells": {m: len(by[m]) for m in METHODS if m in by}, "replaced_cells_excluded": len(skipped), "methods": {},
           "comparisons": {}, "per_change": {}}
    boots = {}
    mean = lambda xs: sum(xs) / len(xs) if xs else None
    for m in METHODS:
        if m not in by:
            continue
        cs = by[m]
        row = {"name": NAMES[m], "cells": len(cs), "provider_errors": sum(c["errors"] for c in cs), "run_acc": {}}
        for g, ps in S.GROUPS.items():
            b = S.boot(cs, ps, o.reps, rnd)
            boots[(m, g)] = b
            row[g] = {"acc": S.rate(cs, ps), "ci95": S.ci(b)}
            row["run_acc"][g] = [S.rate([c], ps) for c in cs]
        row["stale_tasks"] = {g: sum(c["stale"].get(p, 0) for c in cs for p in ps) for g, ps in S.GROUPS.items() if g != "all"}
        row["revoked_per_cell"] = sum(c["revoked"] for c in cs) / len(cs)
        row["repaired_per_cell"] = sum(c["repaired"] for c in cs) / len(cs)
        calls, toks, secs = timing[m]
        row["llm_calls_per_task"], row["input_tokens_per_task"], row["seconds_per_task"] = mean(calls), mean(toks), mean(secs)
        res["methods"][m] = row
        res["per_change"][m] = {p: S.rate(cs, [p]) for p in S.PHASES}

    def diff(a, b, g):
        if (a, g) not in boots or (b, g) not in boots:
            return None
        xa, xb = boots[(a, g)], boots[(b, g)]
        n = min(len(xa), len(xb))
        return {"diff": res["methods"][a][g]["acc"] - res["methods"][b][g]["acc"], "ci95": S.ci([xa[i] - xb[i] for i in range(n)])}

    res["comparisons"] = {
        # 预先写定的分析方案（exp/2026-10-12-reforce/README.md）
        "a1 modeled: +MAVRA - alone": diff("reforce-mavra", "reforce", "modeled"),
        "a2 modeled: +MAVRA - examples": diff("reforce-mavra", "reforce-traj", "modeled"),
        "a3 modeled: +MAVRA - written once": diff("reforce-mavra", "reforce-static", "modeled"),
        "b holdout: +MAVRA - alone": diff("reforce-mavra", "reforce", "holdout"),
        "c all: +MAVRA - alone": diff("reforce-mavra", "reforce", "all"),
    }
    res["comparisons"] = {k: v for k, v in res["comparisons"].items() if v is not None}
    if o.json:
        json.dump(res, open(o.json, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    if o.tex_out:
        tex(res, o.tex_out)
    print(json.dumps({m: {g: r[g]["acc"] for g in S.GROUPS} for m, r in res["methods"].items()}, ensure_ascii=False, indent=1))
    print(json.dumps(res["comparisons"], ensure_ascii=False, indent=1))


if __name__ == "__main__":
    main()
