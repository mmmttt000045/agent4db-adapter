#!/usr/bin/env python3
"""Generate scenario and repair-regression tables from archived per-run counts.

    python3 tools/scenario-summary.py

Writes overleaf/gen/{scenario-summary,repair-regression}.tex. The supplement retains held-out and
all-setting results and separates unit scaling from backup copies. Original
experiment JSON is read only. Values are pooled within each scenario, then
averaged equally across scenarios; parentheses are run ranges, not CIs.
"""
import json
from math import isclose
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
METHODS = [
    ('middle', 'No-Memory', '无指标记忆'),
    ('traj-global', 'Traj-Retrieve', '轨迹检索'),
    ('traj-verify', 'Traj-PromptVerify', '轨迹+提示核验'),
    ('metric-global-schema', 'Metric-Schema', '结构兼容检查'),
    ('metric-global-revoke', 'Metric-Relearn', '写入即重学'),
    ('metric-global-def', 'Maint-DefLevel', '整定义重查'),
    ('metric-global-snap', 'MAVRA', '学习快照回归'),
    ('metric-global-exref', 'MAVRA-CurrData', '当前数据回归'),
    ('metric-global', 'MAVRA-OracleRef', '真值参照回归'),
]
PHASES = {
    'holdout': ['holdout'],
    'benign': ['append', 'backfill', 'correct', 'addcol'],
    'modeled': ['status', 'revision', 'dupload', 'dimhist', 'latekey'],
    'unit': ['unit'],
    'mirror': ['mirror'],
}
PHASES['all'] = [p for phases in PHASES.values() for p in phases]
PANELS = [
    ('Synthetic retail: five runs per method', '合成零售数据：每种方法五次运行',
     'exp/2026-10-10-scenarios-q5/scen-stats.json'),
    ('TPC-H SF1: three runs per method', 'TPC-H SF1：每种方法三次运行',
     'exp/2026-10-11-generality/e2e/scen-stats.json'),
]


def rate(runs, phases):
    values = []
    for phase in phases:
        correct = sum(r['acc'].get(phase, [0, 0])[0] for r in runs)
        total = sum(r['acc'].get(phase, [0, 0])[1] for r in runs)
        if not total:
            raise ValueError(f'No scored questions for {phase}')
        values.append(correct / total)
    return 100 * sum(values) / len(values)


def render():
    lines = ['% Generated by tools/scenario-summary.py; do not edit.',
             r'\newcommand{\ScenarioSummaryRows}{%']
    for en, zh, filename in PANELS:
        data = json.loads((ROOT / filename).read_text(encoding='utf-8'))['methods']
        assert set(data) <= {mode for mode, *_ in METHODS}, filename
        title = r'\multicolumn{7}{@{}l@{}}{\textbf{\bt{' + en + '}{' + zh + r'}}}\\'
        lines += [title, r'\midrule']
        for mode, short, chinese in METHODS:
            if mode not in data:
                continue
            method = data[mode]
            cells = []
            for group, phases in PHASES.items():
                pooled = rate(method['runs'], phases)
                assert isclose(pooled, 100 * method[group]['acc'], abs_tol=1e-10), (filename, mode, group)
                # Compare the same scenarios across runs. Provider failures
                # leave two entire scenarios unscored in synthetic exref r5.
                runs = [rate([r], phases) for r in method['runs']
                        if all(r['acc'].get(p, [0, 0])[1] for p in phases)]
                mark = r'\textsuperscript{*}' if len(runs) < len(method['runs']) else ''
                cells.append(rf'\shortstack{{{pooled:.1f}{mark}\\{{\scriptsize ({min(runs):.1f}--{max(runs):.1f})}}}}')
            name = rf'\bt{{{short}}}{{{chinese}}}'
            if mode == 'metric-global-snap':
                name = rf'\textbf{{{name}}}'
            lines.append(name + ' & ' + ' & '.join(cells) + r'\\')
        lines.append(r'\addlinespace')
    return '\n'.join(lines + ['}']) + '\n'


def render_regression():
    """Compact main-paper results; run details remain in the artifact table."""
    data = json.loads((ROOT / PANELS[0][2]).read_text(encoding='utf-8'))['methods']
    modes = {'metric-global-def', 'metric-global-snap', 'metric-global-exref', 'metric-global'}
    groups = ('modeled', 'unit', 'mirror')
    lines = ['% Generated by tools/scenario-summary.py; do not edit.',
             r'\newcommand{\RepairRegressionRows}{%']
    for mode, short, chinese in METHODS:
        if mode not in modes:
            continue
        method = data[mode]
        cells = []
        for group in groups:
            phases = PHASES[group]
            pooled = rate(method['runs'], phases)
            assert isclose(pooled, 100 * method[group]['acc'], abs_tol=1e-10), (mode, group)
            cells.append(f'{pooled:.1f}')
        name = rf'\bhl{{{short}}}{{{chinese}}}'
        if mode == 'metric-global-snap':
            name = rf'\textbf{{{name}}}'
        lines.append(name + ' & ' + ' & '.join(cells) + r'\\')
    lines.append('}')
    for mode, macro in [('metric-global-snap', 'RgMavraStructural'),
                        ('metric-global-exref', 'RgCurrentStructural'),
                        ('metric-global', 'RgOracleStructural')]:
        value = rate(data[mode]['runs'], PHASES['modeled'])
        lines.append(rf'\newcommand{{\{macro}}}{{{value:.1f}}}')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    for filename, contents in [('scenario-summary', render()), ('repair-regression', render_regression())]:
        path = ROOT / f'overleaf/gen/{filename}.tex'
        path.write_text(contents, encoding='utf-8')
        print(path)
